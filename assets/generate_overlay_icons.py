"""Pack approved C-style sprites; 32texels displayed at 8 map pixels, zero transparent."""
from pathlib import Path
from PIL import Image, ImageDraw
from pixel_icons import load_icon

R = Path(__file__).resolve().parent
TEX, SCALE = 32, 4


def puzzle_marker():
    icon = Image.new('RGB', (TEX,TEX))
    d = ImageDraw.Draw(icon)
    # Dark rim (~1 map pixel at 6px draw size) keeps the amber diamond readable on orange pending rooms.
    d.polygon(((16,1),(31,16),(16,31),(1,16)), fill=(8,8,8))
    d.polygon(((16,7),(25,16),(16,25),(7,16)), fill=(238,184,48))
    mark_exclamation(d)
    return icon


def mark_exclamation(d):
    # RE0 rule (user 2026-11-08): the puzzle diamond carries a dark '!' (bar and dot).
    d.rectangle((15,10,16,17), fill=(8,8,8))
    d.rectangle((15,20,16,21), fill=(8,8,8))


def event_marker():
    # Events (spoiler story scenes): purple diamond (#B070FF, RE0 event colour) with a dark '?'.
    icon = Image.new('RGB', (TEX,TEX))
    d = ImageDraw.Draw(icon)
    d.polygon(((16,1),(31,16),(16,31),(1,16)), fill=(8,8,8))
    d.polygon(((16,7),(25,16),(16,25),(7,16)), fill=(176,112,255))
    d.line(((13,12),(13,11),(14,10),(17,10),(18,11),(18,13),(16,15),(16,17)), fill=(8,8,8), width=1)
    d.rectangle((15,20,16,21), fill=(8,8,8))
    return icon


def key_star():
    # [3] key-item marker: star in the item-label cyan (generate_item_labels.FILL, the old dot colour), dark rim;
    # drawn after the puzzle diamond so it stays on top and contrasts with the amber diamond.
    icon = Image.new('RGB', (TEX, TEX))
    d = ImageDraw.Draw(icon)
    d.polygon(MONSTER_STAR, fill=(8, 8, 8))
    d.polygon([(16 + (x - 16) * 0.55, 17 + (y - 17) * 0.55) for x, y in MONSTER_STAR], fill=(136, 232, 255))
    return icon


def puzzle_key():
    # Key item on a puzzle spot, drawn at 7 px (same as the key star) in place of the 6 px diamond. The native map filters textures bilinearly, so
    # a small cyan core blends into the amber (user 2026-10-23 screenshot: pale yellow); the cyan star fills ~70% of
    # the diamond with a thin dark outline and the amber shows between its points.
    icon = Image.new('RGB', (TEX, TEX))
    d = ImageDraw.Draw(icon)
    d.polygon(((16,0),(31,16),(16,31),(0,16)), fill=(8,8,8))
    d.polygon(((16,2),(29,16),(16,29),(2,16)), fill=(238,184,48))
    d.polygon([(16 + (x - 16) * 0.85, 17 + (y - 17) * 0.85) for x, y in MONSTER_STAR], fill=(8, 8, 8))
    d.polygon([(16 + (x - 16) * 0.7, 17 + (y - 17) * 0.7) for x, y in MONSTER_STAR], fill=(136, 232, 255))
    return icon


def map_icon():
    icon = Image.new('RGB', (TEX,TEX))
    d = ImageDraw.Draw(icon)
    d.polygon(((3,7),(11,3),(21,7),(28,3),(28,25),(21,29),(11,25),(3,29)), fill=(64,56,40))
    d.polygon(((5,8),(10,6),(10,23),(5,25)), fill=(184,168,120))
    d.polygon(((12,6),(20,9),(20,26),(12,23)), fill=(224,208,160))
    d.polygon(((22,9),(26,7),(26,23),(22,26)), fill=(160,144,104))
    d.line(((7,19),(14,13),(18,17),(24,12)), fill=(88,104,72), width=2)
    return icon


# Category order follows extract_monsters.CATEGORY; artwork: monster-icons-v2 (Evil Resource RE2 references).
from extract_monsters import CATEGORY_NAMES as MONSTER_NAMES
MONSTER_STAR = [(16, 1), (20, 11), (31, 12), (22, 19), (25, 30), (16, 24), (7, 30), (10, 19), (1, 12), (12, 11)]


def rgb555(page):
    # Opaque black must not become 0 (transparent).
    return [((r >> 3) | ((g >> 3) << 5) | ((b >> 3) << 10)) or 0x421 if (r, g, b) != (0, 0, 0) else 0
            for r, g, b in page.get_flattened_data()]


def generate():
    page = Image.new('RGB', (256, 256))
    icons = [(kind, name, puzzle_marker() if kind==12 else load_icon(name, (TEX,TEX))) for kind,name in
             ((9,'typewriter'),(10,'itembox'),(11,'document'),(12,'puzzle'))]
    pickups = (20,21,22,24,25,26,27,29,30,35,38,39,40)
    ammo = (20,21,22,24,25,26,27,29)
    assert len({load_icon(f'pickup-{item}', (TEX,TEX)).tobytes() for item in ammo}) == len(ammo)
    icons += [(100 + item, f'pickup-{item}', load_icon(f'pickup-{item}', (TEX,TEX))) for item in pickups]
    icons.append((13, 'map', map_icon()))
    icons.append((14, 'keystar', key_star()))
    icons.append((15, 'puzzle-key', puzzle_key()))
    icons.append((16, 'event', event_marker()))
    heads = [load_icon('monster-' + name, (TEX, TEX)) for name in MONSTER_NAMES]
    assert len({im.tobytes() for im in heads}) == len(MONSTER_NAMES) == 12
    icons += [(50 + c, 'monster-' + name, heads[c]) for c, name in enumerate(MONSTER_NAMES)]
    rows = []
    for i, (kind, name, im) in enumerate(icons):
        u, v = 1 + (i % 7) * (TEX + 2), 1 + (i // 7) * (TEX + 2)
        page.paste(im, (u, v)); rows.append((kind, u, v, name))
    pixels = rgb555(page)
    assert all(pixels[v * 256 + u] == 0 for u in range(256) for v in range(256)
               if not any(ru <= u < ru + TEX and rv <= v < rv + TEX for _, ru, rv, _ in rows))
    out = ['/* Generated by generate_overlay_icons.py; RGB555, zero transparent. Draw at w/OVERLAY_ICON_SCALE. */',
           '#ifndef RE2_OVERLAY_ICONS_H', '#define RE2_OVERLAY_ICONS_H',
           f'#define OVERLAY_ICON_TEX {TEX}', f'#define OVERLAY_ICON_SCALE {SCALE}',
           'typedef struct { unsigned char kind,u,v; } OverlayIcon;',
           'static const OverlayIcon overlay_icons[] = {'] + ['{%d,%d,%d}, /* %s */' % r for r in rows]
    out += ['};', 'static const unsigned short overlay_icon_pixels[65536]={' + ','.join(hex(p) for p in pixels) + '};', '#endif', '']
    (R / 'overlay_icons.h').write_text('\n'.join(out))
    preview = Image.new('RGB', (360, 200), (28, 32, 35))
    for i, (_, _, im) in enumerate(icons):
        mask = im.convert('L').point(lambda p: 255 if p else 0)
        small = (TEX // SCALE * 4,) * 2  # 8px map icon, zoomed 4x
        x, y = 8 + (i % 7) * 48, 4 + (i // 7) * 64
        preview.paste(im.resize(small, Image.Resampling.NEAREST), (x, y), mask.resize(small))
        preview.paste(im, (x + 16, y), mask)
    preview.save(R / 'overlay_icons-preview.png')
    print(rows)


if __name__ == '__main__':
    generate()
