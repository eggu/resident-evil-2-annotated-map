"""Pack the Codex-drawn key-item sprites (assets/key-art-provenance.json) into a second 256x256 RGB555 page.

Sprites keep their drawn size (<=32 px, binary alpha) and are not resized, so the page is a 1:1 copy. The lock-icon page
(generate_atlas.py) is full. Output: key_art.h with KeyArt{item,u,v,w,h} rows (w/h = visible texels) and key_art_pixels.
"""
from pathlib import Path
import json
from PIL import Image

R = Path(__file__).resolve().parent
ids = sorted(int(r['id']) for r in json.loads((R/'key-art-provenance.json').read_text())['entries'])
sprites = []
for item in ids:
    im = Image.open(R/'icons'/f'key-{item}.png').convert('RGBA')
    assert max(im.size) <= 32 and set(im.getchannel('A').get_flattened_data()) <= {0, 255}
    im = im.crop(im.getchannel('A').getbbox())
    assert len({p for p in im.get_flattened_data() if p[3]}) <= 16
    sprites.append((item, im))
# Shelf packing, tallest first, 1 px transparent gap so bilinear sampling never bleeds a neighbour.
page = [0]*65536; rows = []; x = y = shelf = 0
for item, im in sorted(sprites, key=lambda s: (-s[1].height, s[0])):
    if x + im.width + 1 > 256:
        x, y, shelf = 0, y + shelf + 1, 0
    assert y + im.height + 1 <= 256, 'key art page full'
    u, v = x + 1, y + 1
    for py in range(im.height):
        for px in range(im.width):
            r, g, b, a = im.getpixel((px, py))
            # Opaque black must not become 0 (transparent).
            page[(v+py)*256 + u+px] = (((r >> 3) | ((g >> 3) << 5) | ((b >> 3) << 10)) or 0x421) if a else 0
    rows.append((item, u, v, im.width, im.height))
    x += im.width + 1; shelf = max(shelf, im.height + 1)
rows.sort()
out = ['/* Generated by generate_key_art.py; RGB555, zero transparent, 1:1 sprites. */', '#ifndef RE2_KEY_ART_H', '#define RE2_KEY_ART_H',
       'typedef struct {unsigned char item,u,v,w,h;} KeyArt;',
       'static const KeyArt key_art[]={' + ','.join('{%d,%d,%d,%d,%d}' % r for r in rows) + '};',
       'static const unsigned short key_art_pixels[65536]={' + ','.join(hex(p) for p in page) + '};', '#endif', '']
(R/'key_art.h').write_text('\n'.join(out))
preview = Image.new('RGB', (256*2, 256*2), (28, 32, 35))
for item, u, v, w, h in rows:
    for py in range(h):
        for px in range(w):
            p = page[(v+py)*256 + u+px]
            if p:
                c = ((p & 31) << 3, (p >> 5 & 31) << 3, (p >> 10 & 31) << 3)
                for dy in range(2):
                    for dx in range(2): preview.putpixel(((u+px)*2+dx, (v+py)*2+dy), c)
preview.save(R/'key_art-preview.png')
print('Packed', len(rows), 'key sprites; page rows used up to y =', y + shelf)
