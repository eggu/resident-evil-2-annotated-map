"""Open side of every door row (user 2026-11-13): the lock marker goes beside the door on the side of its own room (the room it is drawn
for, open to the player), never in the locked room behind it. The rect centre of a room is no guide (an L-shaped corridor's rect covers
the rooms beside it), so this probes the room masks: from the door spot, 2..10 px out along each axis direction, own-room cells against
destination-room cells; the direction with the most own-room and no more destination cells wins. -> src/door_sides.h (parallel to doors[])."""
import json, re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]


def rect_cells(r):
    return {(r['x'] + x, r['y'] + j) for j, runs in enumerate(r['runs']) for a, n in runs for x in range(a, min(a + n, r['w']))}


def main():
    shapes = {(f['pl'], f['floor']): {r['seen']: rect_cells(r) for r in f['rooms']} for f in json.loads((ROOT / 'data/room_shapes.json').read_text())['floors']}
    text = (ROOT / 'src/doors-all.h').read_text()
    rows = [tuple(int(v) for v in re.findall(r'-?\d+', m)) for m in re.findall(r'\{([^{}]*)\}', text[text.index('doors[]') :])]
    out, found = [], 0
    for pl, floor, x, y, seen, unlock, key, sm, bank, x1, y1, x2, y2, seen2 in rows:
        best = (0, 0)
        rooms = shapes.get((pl & 1, floor), {})
        if seen2 != 255 and seen in rooms:
            own, dest = rooms[seen], rooms.get(seen2, set())
            cx, cy = x + 3, y + 3   # inside the 8x8 bar sprite (a projected row has none; its spot is close enough)
            score = {}
            for d in ((-1, 0), (1, 0), (0, -1), (0, 1)):
                pts = [(cx + d[0] * t, cy + d[1] * t) for t in range(2, 11)]
                score[d] = sum(p in own for p in pts) - 2 * sum(p in dest for p in pts)
            d, v = max(score.items(), key=lambda kv: kv[1])
            if v > 0: best = d
        found += best != (0, 0)
        out.append('{%d,%d}' % best)
    (ROOT / 'src/door_sides.h').write_text('/* generated by tools/mapgen/door_sides.py: per doors[] row, the unit step towards the open (own) room; {0,0} none */\n'
                                           'static const signed char door_sides[][2]={' + ','.join(out) + '};\n')
    print(len(rows), 'doors,', found, 'with an open side')


if __name__ == '__main__':
    main()
