"""Glyph page for the live rank line on the map legend (digits, A-E, words in both languages)."""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

R = Path(__file__).resolve().parent
FONT = Path(__file__).resolve().parent / 'fonts/Pretendard-SemiBold.otf'  # open font only (release rule 2026-10-26)
FONT_PX, STROKE = 16, 1  # same as the legend (generate_room_names HELP_FONT_PX/HELP_STROKE); drawn at 1/4
FILL, OUTLINE = (248, 240, 200), (8, 8, 8)
# Token ids used by re2_keymap.c: 0-9 digits, 10 ':', 11-15 'A'-'E', then words (EN set, KO set).
GLYPHS = [str(d) for d in range(10)] + [':'] + list('ABCDE')
WORDS_EN = ['RANK', 'pts', 'SAVE', 'SPRAY', 'INF -50']
WORDS_KO = ['랭크', '점', '세이브', '스프레이', '무한 무기 -50']


def generate():
    font = ImageFont.truetype(str(FONT), FONT_PX)
    page = Image.new('RGB', (256, 256))
    draw = ImageDraw.Draw(page)
    defs, x, y, row_h = [], 1, 1, 0
    for text in GLYPHS + WORDS_EN + WORDS_KO:
        box = font.getbbox(text, stroke_width=STROKE)
        w, h = box[2] - box[0] + 2, box[3] - box[1] + 2
        if x + w + 1 > 256:
            x, y, row_h = 1, y + row_h + 2, 0
        assert y + h + 1 <= 256
        draw.text((x + 1 - box[0], y + 1 - box[1]), text, font=font, fill=FILL, stroke_width=STROKE, stroke_fill=OUTLINE)
        defs.append((x, y, w, h, text))
        x, row_h = x + w + 2, max(row_h, h)
    # Common baseline: every glyph cell uses the tallest digit height so the line does not jitter.
    pixels = [((r >> 3) | ((g >> 3) << 5) | ((b >> 3) << 10)) or 0x421 if (r, g, b) != (0, 0, 0) else 0
              for r, g, b in page.get_flattened_data()]
    out = ['/* Generated by generate_rank_glyphs.py; RGB555 zero transparent; draw at 1/4. */',
           '#ifndef RE2_RANK_GLYPHS_H', '#define RE2_RANK_GLYPHS_H',
           f'#define RANK_WORD_EN {len(GLYPHS)}', f'#define RANK_WORD_KO {len(GLYPHS) + len(WORDS_EN)}',
           'typedef struct { unsigned char u,v,w,h; } RankGlyph;', 'static const RankGlyph rank_glyphs[] = {']
    out += ['{%d,%d,%d,%d}, /* %s */' % d for d in defs]
    out += ['};', 'static const unsigned short rank_glyph_pixels[65536]={' + ','.join(hex(p) for p in pixels) + '};', '#endif', '']
    (R / 'rank_glyphs.h').write_text('\n'.join(out))
    page.save(R / 'rank_glyphs-preview.png')
    print('rank glyphs', len(defs))


if __name__ == '__main__':
    generate()
