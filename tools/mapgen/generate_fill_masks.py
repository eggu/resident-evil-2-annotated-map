"""Room-fill shape masks (map TIM page 0x20, CLUT index 1) per map floor, for the colour-blind-safe pending tint."""
from pathlib import Path
import struct

R = Path(__file__).resolve().parent
# Floor -> map file id: EXE floor table word +6 (0x53eaf8; Claire's table has the same ids).
FLOOR_MAPS = (0, 1, 10, 2, 3, 11, 20, 30, 31, 40, 41, 42, 43, 50, 51, 52, 53, 54, 60, 61)


def fill_page(map_id):
    # map60/61 plain files lack the fill page; the 'd' variant's shape pages are byte-identical (maps-report.md).
    name = f'map{map_id:02d}.bin'
    d = (R / 'maps-decoded' / name).read_bytes()
    if d[0x10080:0x10088] != bytes.fromhex('1000000008000000'):
        d = (R / 'maps-decoded' / name.replace('.bin', 'd.bin')).read_bytes()
    o = 0x10080
    assert struct.unpack_from('<II', d, o) == (0x10, 8), name  # 4bpp TIM with CLUT
    p = o + 8 + struct.unpack_from('<I', d, o + 8)[0]
    _, _, _, w, h = struct.unpack_from('<IHHHH', d, p)
    assert (w * 4, h) == (256, 256), name
    return d[p + 12:p + 12 + 128 * 256]


def mask(map_id):
    px = fill_page(map_id)
    bits = bytearray(8192)
    for i, b in enumerate(px):
        for n, idx in ((0, b & 15), (1, b >> 4)):
            if idx == 1:  # the room-colour entry (blue/red in rows 0-3)
                q = i * 2 + n
                bits[q >> 3] |= 0x80 >> (q & 7)
    return bytes(bits)


def generate():
    rows = [mask(m) for m in FLOOR_MAPS]
    out = ['/* Generated by generate_fill_masks.py: 256x256 1-bit room-fill masks per map floor, MSB first. */',
           '#ifndef RE2_FILL_MASKS_H', '#define RE2_FILL_MASKS_H', f'#define FILL_MASK_FLOORS {len(rows)}',
           'static const unsigned char fill_masks[FILL_MASK_FLOORS][8192]={']
    out += ['{' + ','.join(str(b) for b in r) + '},' for r in rows]
    out += ['};', '#endif', '']
    (R / 'fill_masks.h').write_text('\n'.join(out))
    print('fill masks', [sum(bin(b).count('1') for b in r) for r in rows])


if __name__ == '__main__':
    generate()
